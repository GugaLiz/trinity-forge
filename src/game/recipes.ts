export const RECIPE_MAP = Object.fromEntries(RECIPES.map((r) => [r.id, r])) as Record<
  string,
  Recipe
>;
export function isElement(token: string): token is Element {
  return Object.hasOwn(ELEMENTS, token);
}
export function tokenName(token: string) {
  return isElement(token) ? ELEMENTS[token].name : (RECIPE_MAP[token]?.name ?? '未知');
}
export function tokenGlyph(token: string) {
  return isElement(token) ? ELEMENTS[token].glyph : (RECIPE_MAP[token]?.glyph ?? 'spark');
}
export function matchRecipe(tokens: string[]): Recipe | undefined {
  return RECIPES.find(
    (r) =>
      r.inputs.length === tokens.length &&
      (r.ordered
        ? r.inputs.every((token, i) => token === tokens[i])
        : [...r.inputs].sort().join('|') === [...tokens].sort().join('|')),
  );
}
